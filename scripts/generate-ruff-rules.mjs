import { execFile } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { promisify } from 'node:util'

// Pin the CLI so catalog generation is reproducible across machines.
const ruffVersion = '0.16.8'
const { stdout: output } = await promisify(execFile)(
  'uv',
  [
    'tool',
    'run',
    '--from',
    `ruff==${ruffVersion}`,
    'ruff',
    'rule',
    '--all',
    '--output-format',
    'json',
  ],
  { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 },
)
const definitions = JSON.parse(output)
// Preview, removed and deprecated rules require separate compatibility choices.
const stableRules = definitions.filter((rule) => Object.hasOwn(rule.status, 'Stable'))
const ruffRules = stableRules.map((rule) => ({
  group: 'ruff',
  name: rule.code,
  title: rule.name,
  summary: `${rule.name}: ${rule.summary}`,
  url: `https://docs.astral.sh/ruff/rules/${rule.name}/`,
  domains: [rule.linter],
  categories: ['Python'],
}))
const domainLabels = Object.fromEntries(
  [...new Set(stableRules.map((rule) => rule.linter))].sort().map((name) => [name, name]),
)
writeFileSync(
  new URL('../src/domain/ruffRules.ts', import.meta.url),
  `// Generated by scripts/generate-ruff-rules.mjs. Do not edit.\nimport type { BiomeRule } from './types'\nexport const ruffRules: BiomeRule[] = ${JSON.stringify(ruffRules, null, 2)}\nexport const ruffVersion = '${ruffVersion}'\nexport const ruffDomainLabels = ${JSON.stringify(domainLabels, null, 2)}\n`,
)
console.log(`Generated ${ruffRules.length} stable Ruff rules.`)
