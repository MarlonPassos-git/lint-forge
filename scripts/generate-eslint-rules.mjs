import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import typescript from '@typescript-eslint/eslint-plugin'
import { builtinRules } from 'eslint/use-at-your-own-risk'
import hooks from 'eslint-plugin-react-hooks'

const require = createRequire(import.meta.url)
const sources = [
  {
    group: 'eslint',
    package: 'eslint',
    rules: Object.fromEntries(builtinRules),
    categories: ['JavaScript'],
    label: 'ESLint core',
  },
  {
    group: '@typescript-eslint',
    package: '@typescript-eslint/eslint-plugin',
    rules: typescript.rules,
    categories: ['TypeScript'],
    label: 'TypeScript',
  },
  {
    group: 'react-hooks',
    package: 'eslint-plugin-react-hooks',
    rules: hooks.rules,
    categories: ['JavaScript', 'TypeScript'],
    label: 'React Hooks',
  },
]

const eslintRules = sources.flatMap((source) =>
  Object.entries(source.rules)
    .filter(([, rule]) => !rule.meta.deprecated && rule.meta.docs?.url)
    .map(([name, rule]) => ({
      group: source.group,
      name,
      title: name,
      summary: rule.meta.docs.description,
      url: rule.meta.docs.url,
      domains: [source.group],
      categories: source.categories,
      requiresTypeChecking: rule.meta.docs.requiresTypeChecking === true,
    })),
)
const versions = Object.fromEntries(
  sources.map((source) => [source.package, require(`${source.package}/package.json`).version]),
)
const labels = Object.fromEntries(sources.map((source) => [source.group, source.label]))
const source = `// Generated by scripts/generate-eslint-rules.mjs. Do not edit.\nimport type { BiomeRule } from './types'\nexport const eslintRules: BiomeRule[] = ${JSON.stringify(eslintRules, null, 2)}\nexport const eslintVersions = ${JSON.stringify(versions, null, 2)}\nexport const eslintDomainLabels = ${JSON.stringify(labels, null, 2)}\n`
writeFileSync(new URL('../src/domain/eslintRules.ts', import.meta.url), source)
console.log(`Generated ${eslintRules.length} ESLint rules.`)
